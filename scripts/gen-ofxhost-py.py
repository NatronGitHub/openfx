"""Generate the ofxhost Python modules from the headers in include/.

- ofxhost/constants.py: every `#define kName value` of include/ (strings, integers, floats,
  booleans, and macros defined as another one), with the C name, e.g. constants.kOfxImageEffectPropContext.
- ofxhost/props.py: the @propdef metadata of every property (type, dimension, valid values,
  extension), plus aliases. See scripts/ofx_fork_props.py for how it is read and checked.

usage: scripts/gen-ofxhost-py.py [--check]
  --check: don't write, exit with status 1 if the committed files are out of date (CI).

Needs PyYAML. The generated modules don't.
"""
import re
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))

import ofx_fork_props  # noqa: E402

INCLUDE = ofx_fork_props.INCLUDE
OUT = SCRIPTS.parent / "HostSupport" / "examples" / "python" / "ofxhost"
HEADER = "# SPDX-License-Identifier: BSD-3-Clause\n# Generated by scripts/gen-ofxhost-py.py from include/. DO NOT EDIT.\n"

_DEFINE = re.compile(r'^[ \t]*#[ \t]*define[ \t]+(k\w+)[ \t]+(.*?)[ \t]*(?:/\*.*|//.*)?$', re.M)
_INT = re.compile(r'\(*\s*(?:\(\s*(?:unsigned\s+)?int\s*\)\s*)?(-?(?:0[xX][0-9a-fA-F]+|\d+))[uUlL]*\s*\)*')

_LIMITS = {"INT_MAX": 2**31 - 1, "INT_MIN": -2**31}  # int is 32-bit on every OFX platform


def parse_value(text):
    """(kind, value) of a #define body: str, int, float, bool, alias (another kName), or None."""
    if re.fullmatch(r'"[^"\\]*"', text):
        return "str", text[1:-1]
    if text in ("true", "false"):
        return "bool", text == "true"
    m = _INT.fullmatch(text)
    if m and text.count("(") == text.count(")"):
        return "int", int(m.group(1), 0)
    if re.fullmatch(r'-?\d+\.\d*([eE][-+]?\d+)?', text):
        return "float", float(text)
    if text in _LIMITS:
        return "int", _LIMITS[text]
    if re.fullmatch(r'k\w+', text):
        return "alias", text
    return None, None


def constants():
    """{cname: (value, header)}, sorted by header then position; aliases resolved."""
    raw, skipped = {}, []
    for header in ofx_fork_props.headers(INCLUDE):
        rel = str(header.relative_to(INCLUDE))
        for cname, body in _DEFINE.findall(header.read_text()):
            kind, value = parse_value(body)
            if kind is None:
                skipped.append(f"{rel}: {cname} {body}")
                continue
            if cname in raw and raw[cname][:2] != (kind, value):
                raise ValueError(f"{cname} has two values: {raw[cname]} and {(kind, value, rel)}")
            raw.setdefault(cname, (kind, value, rel))
    out = {}
    for cname, (kind, value, rel) in raw.items():
        seen = {cname}
        while kind == "alias":
            if value not in raw or value in seen:
                raise ValueError(f"{cname}: cannot resolve {value}")
            seen.add(value)
            kind, value, _ = raw[value]
        out[cname] = (value, rel)
    return out, skipped


def gen_constants(consts):
    lines = [HEADER, '"""OFX constants from the C headers (include/), with their C names.\n\n'
             'Strings, integers (status codes, key symbols...), floats and booleans; macros defined as\n'
             'another macro are resolved."""\n']
    last = None
    for cname, (value, rel) in consts.items():
        if rel != last:
            lines.append(f"\n# {rel}")
            last = rel
        lines.append(f"{cname} = {value!r}")
    return "\n".join(lines) + "\n"


def gen_props(consts):
    md = ofx_fork_props.all_inline_metadata(INCLUDE)
    classes, unclassified = ofx_fork_props.classify(INCLUDE)
    if unclassified:
        raise SystemExit("unclassified #defines, run scripts/check-props.py")
    out = [HEADER, '''"""OFX property metadata, from the @propdef blocks of the C headers (include/).

PROPS maps the property name (its string value, e.g. "OfxPropLabel") to a PropDef.
dimension 0 means any number of values (N in the headers). For enum properties, values
also lists the extension values and the deprecated ones.
"""
from typing import NamedTuple, Optional, Tuple, Union


class PropDef(NamedTuple):
    name: str
    cname: str
    # string, enum, int, bool, double or pointer; a tuple of them if the type depends on the
    # parameter (e.g. OfxParamPropDefault)
    type: Union[str, Tuple[str, ...]]
    dimension: int
    values: Tuple = ()
    extension: Optional[str] = None  # None for standard properties, else natron, nuke, vegas...
    introduced: Optional[str] = None
    deprecated: Optional[str] = None
    header: str = ""


PROPS = {''']
    for name in sorted(md):
        d = md[name]
        m = d["metadata"]
        dim = m.get("dimension")
        dim = 0 if dim in ("N", 0) else int(dim)
        values = list(m.get("values") or [])
        for c in ofx_fork_props.EXTRA_VALUES.get(name, []):
            v = consts[c][0]
            if v not in values:
                values.append(v)
        typ = tuple(m["type"]) if isinstance(m["type"], list) else m["type"]
        args = [repr(name), repr(d["cname"]), repr(typ), str(dim)]
        if values:
            args.append(f"values={tuple(values)!r}")
        for key in ("extension", "introduced", "deprecated"):
            if m.get(key) is not None:
                args.append(f"{key}={str(m[key])!r}")
        args.append(f"header={d['header']!r}")
        out.append(f"    {name!r}: PropDef({', '.join(args)}),")
    out.append("}\n")
    aliases = {c: info for c, (kind, info) in sorted(classes.items()) if kind == "alias"}
    out.append("# other C names of a property (same string value): {C name: C name of the property}")
    out.append("ALIASES = {")
    out += [f"    {c!r}: {target!r}," for c, target in aliases.items()]
    out.append("}\n")
    out.append("BY_CNAME = {p.cname: p for p in PROPS.values()}")
    out.append("BY_CNAME.update({a: BY_CNAME[c] for a, c in ALIASES.items()})\n")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    consts, _ = constants()
    files = {OUT / "constants.py": gen_constants(consts), OUT / "props.py": gen_props(consts)}
    stale = []
    for path, text in files.items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(SCRIPTS.parent)}")
    if stale:
        for p in stale:
            print(f"{p.relative_to(SCRIPTS.parent)} is out of date: run scripts/gen-ofxhost-py.py", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
